private val LocalTechTicketColors = staticCompositionLocalOf { DarkTechTicketColors }

/** Acceso a los colores que Material 3 no incluye (estados de caso, éxito). */
object TechTicketTheme {
    val colors: TechTicketColors
        @Composable
        @ReadOnlyComposable
        get() = LocalTechTicketColors.current
}

// Se conserva el nombre y la firma originales para no tocar MainActivity.
@Composable
fun TechTokensssTheme(
    darkTheme: Boolean = true,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val extraColors = if (darkTheme) DarkTechTicketColors else LightTechTicketColors

    // Los iconos de las barras del sistema siguen el modo elegido en la app
    // (el interruptor de Configuración), no el modo del sistema.
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalTechTicketColors provides extraColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content
        )
    }
}